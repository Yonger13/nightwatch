def build_label_guide(labels: list[str]) -> str:
    """根据实际用到的标签，生成一段"判定参考"文本。

    ★ 只输出**该数据集里真实出现过的标签**，不输出全表 ——
    因为无关标签会干扰模型（它可能去选一个数据集里根本没人用的标签）。
    """
    lines = []
    for lbl in labels:
        desc = LABEL_GUIDE.get(lbl)
        if desc:
            lines.append(f"  · {lbl}：{desc}")
        else:
            lines.append(f"  · {lbl}：（暂无定义，按字面意思理解）")
    return "\n".join(lines) if lines else "  （无）"


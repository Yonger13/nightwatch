def _load_dotenv(path: Path | None = None) -> int:
    """从项目根目录的 `.env` 文件加载环境变量。

    ============================================================
    为什么不直接用 python-dotenv
    ============================================================
    因为这件事只需要十几行代码，而多一个依赖就多一份维护成本
    （版本兼容、安装失败、某些环境下装不上……）。

    这是"先问需不需要，再决定要不要依赖"的又一个例子 ——
    和 Token 估算不引 tiktoken 是同一个判断逻辑。

    ============================================================
    为什么不让用户"每次 export"
    ============================================================
    因为那样很容易忘。忘了之后程序会静默降级到 Mock 模型 ——
    你以为在用真实模型跑评测，实际上跑的是规则版。
    **静默降级是这类配置问题最危险的地方**，所以要让配置"一次配好、长期有效"。

    格式支持（够用就行，不追求完整实现）：
        KEY=value
        KEY="value"        # 引号会被去掉
        export KEY=value   # 兼容 shell 风格
        # 注释

    已存在的环境变量**不会被覆盖** —— 这样命令行临时指定的值优先级更高，
    方便做一次性覆盖（比如临时换个模型试跑）。
    """
    env_path = path or (PROJECT_ROOT / ".env")
    if not env_path.exists():
        return 0

    loaded = 0
    try:
        for raw in env_path.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("export "):
                line = line[7:].strip()
            if "=" not in line:
                continue
            key, _, value = line.partition("=")
            key = key.strip()
            value = value.strip().strip('"').strip("'")
            if key and key not in os.environ:      # 不覆盖已有值
                os.environ[key] = value
                loaded += 1
    except OSError:
        return 0
    return loaded


# 在读取任何配置之前加载 —— 顺序很重要

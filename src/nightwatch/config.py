"""
Nightwatch · 全局配置

================================================================================
这个文件为什么存在
================================================================================
很多 Agent 项目的参数是散落在代码里的魔法数字（"temperature=0.7" 写在某个函数里）。

这里刻意把所有**可调的设计决策**集中到一个文件，原因是：
  1. 这些参数本身就是设计的一部分，不是实现细节。比如"给记忆分配多少上下文预算"
     是一个产品决策，它决定了 Agent 在多大程度上"记得住过去"。
  2. 面试官问"你怎么调的"时，你能指着这个文件说清楚每一个数字的来由。
  3. 做实验时（比如组件组合实验），改参数不用改代码。

================================================================================
关键概念：任务-模型匹配（Task-Model Matching）
================================================================================
MIT 做过一个受控实验（44 张发票 × 4 种模型配置），结论反直觉：
    **能力最强、成本最高的模型配置，反而表现最差。**
结论不是"要用便宜模型"，而是"按任务匹配模型 + 做组件组合测试"。

所以下面 MODEL_ROUTING 是显式设计的：不同任务用不同档次的模型。
这不是省钱的小技巧，是 Agent 系统工程的核心认知 —— 整条链路的配合比单点最强更重要。
================================================================================
"""


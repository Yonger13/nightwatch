@dataclass
class Settings:
    """把上面所有配置聚合成一个对象，方便传入各模块。

    这样设计的好处：测试时可以构造一个改了某几个参数的 Settings，
    不用改全局变量，也不用 monkeypatch。
    """
    model_routing: dict = field(default_factory=lambda: dict(MODEL_ROUTING))
    models: dict = field(default_factory=lambda: dict(MODELS))
    context_budget: dict = field(default_factory=lambda: dict(CONTEXT_BUDGET))
    reliability: dict = field(default_factory=lambda: dict(RELIABILITY))
    memory: dict = field(default_factory=dict)
    tools: dict = field(default_factory=dict)
    eval: dict = field(default_factory=dict)

    # 存储：默认 SQLite，零配置
    db_path: Path = DATA_DIR / "nightwatch.db"
    # 是否使用 Mock LLM（没配 API key 时自动为 True）
    use_mock_llm: bool = not bool(LLM_API_KEY)

    def __post_init__(self):
        # 用 dict(...) 深拷贝，避免调用方修改影响全局
        self.memory = self.memory or {k: (v.copy() if isinstance(v, dict) else v)
                                      for k, v in MEMORY.items()}
        self.tools = self.tools or {k: (v.copy() if isinstance(v, dict) else v)
                                    for k, v in TOOLS.items()}
        self.eval = self.eval or dict(EVAL)


def load_settings() -> Settings:
    """加载默认配置。"""
    return Settings()
